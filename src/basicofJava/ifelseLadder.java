package basicofJava;

public class ifelseLadder {
	
	public static void main(String[] args) {
		
		
		int marks= 80;
		
		if(marks>=90) {
			System.out.println("grade A");
		}
		else if(marks>=75) {
			System.out.println("grade B");
			
		}
		else if(marks>=60) {
			System.out.println("grade C");
		}
		
		else {
			System.out.println("grade D");
		}
		
	}

}
